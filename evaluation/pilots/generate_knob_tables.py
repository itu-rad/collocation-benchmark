#!/usr/bin/env python3
"""Render knobs.yml into per-experiment LaTeX knob tables (stdout).

One booktabs table per experiment: Knob | Value (M2 / GB10) | Rule |
Verification. %-comments carry pilot provenance (filenames, medians, commit,
date) in the same convention as the overhead generate_latex_results.py
scripts. Cells whose pilot hasn't run yet render [[pending pilot]].

    python evaluation/pilots/generate_knob_tables.py > knob_tables.tex
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import pilot_lib as pl  # noqa: E402

EXP_TITLES = {
    "e1": "E1 (NoOp framework overhead)",
    "e2": "E2 (modularity overhead)",
    "e3": "E3 (contention study)",
    "e4": "E4 (Self-RAG topology)",
    "e5": "E5 (MLPerf reduction)",
    "e6": "E6 (collocation scaling)",
}

RULE_TEXT = {
    "R-LAMBDA-BELOW-SAT": r"$\lambda = 0.6\times$ capacity of slowest arm (pilot)",
    "R-LAMBDA-NFLIGHT": r"closed-loop, $N{=}2$ in flight (contended cells)",
    "R-LAMBDA-SAT": r"saturating; throughput-only",
    "R-QDEPTH": r"$=$ max\_queries (never blocks); $\geq$ samples for Offline",
    "R-WARMUP": r"$2\times$ rolling-median flatness point (pilot)",
    "R-NTIMING": r"30--50 queries $\times R$ per timing cell",
    "R-NQUALITY": r"Wilson 95\% half-width $\leq$ 9\,pts (serial runs)",
    "R-REPS": r"runs are the replication unit: 10 cheap / 5 expensive",
    "R-TIMEOUT": r"$5\times$ expected duration (seconds)",
    "R-E6-HEADROOM": r"$\lambda_{fg} = 0.4\times$ capacity; fixed across $B$",
    "R-INTENSITY": r"$\{25,50,75,100\}\%$ of pilot $R_{max}$",
    "R-PRECEDENT": r"external precedent; constant across arms",
}


def _tex_escape(s: str) -> str:
    return (str(s).replace("\\", r"\textbackslash{}").replace("_", r"\_")
            .replace("%", r"\%").replace("&", r"\&").replace("#", r"\#")
            .replace("λ", r"$\lambda$").replace("±", r"$\pm$")
            .replace("<=", r"$\leq$").replace(">=", r"$\geq$")
            .replace(" < ", r" $<$ ").replace(" > ", r" $>$ "))


def _fmt_value(v) -> str:
    if v is None:
        return "[[pending pilot]]"
    if isinstance(v, dict):
        return _tex_escape(", ".join(f"{k}={x}" for k, x in v.items()))
    if isinstance(v, list):
        return _tex_escape(", ".join(str(x) for x in v))
    return _tex_escape(v)


def _key(e: dict) -> str:
    """Display key: knob name, disambiguated by task when a rule binds
    per-task (e.g. E4's factoid vs multihop λ)."""
    task = (e.get("inputs") or {}).get("task")
    return f"{e['knob']} ({task})" if task else e["knob"]


def render_experiment(exp: str, devices: dict, knobs: dict) -> None:
    dev_names = [d for d in ("m2pro", "gb10", "any") if d in devices]
    # union of knob keys, in first-device order
    order, seen = [], set()
    for d in dev_names:
        for e in devices[d] or []:
            if _key(e) not in seen:
                seen.add(_key(e))
                order.append(_key(e))
    by_dev = {d: {_key(e): e for e in (devices[d] or [])} for d in dev_names}

    print(f"% --- {EXP_TITLES.get(exp, exp)} knobs "
          f"(derive_knobs.py @ {knobs.get('git_commit', '?')}, "
          f"{knobs.get('generated', '?')}) ---")
    for d in dev_names:
        for e in devices[d] or []:
            src = (e.get("inputs") or {}).get("pilot")
            if src:
                med = (e.get("inputs") or {}).get("median_service_s")
                print(f"% {d}/{e['knob']}: pilot {src}"
                      + (f" (median {med}s)" if med else ""))
    print("\\begin{table}[t]\\centering\\small")
    print(f"\\caption{{{EXP_TITLES.get(exp, exp)} configuration knobs. Every "
          "value derives from the stated pre-registered rule; pilot inputs and "
          "verification traces are in the artifact.}")
    print(f"\\label{{tab:knobs-{exp}}}")
    ncols = len(dev_names)
    print("\\begin{tabular}{l" + "l" * ncols + "ll}\n\\toprule")
    hdr = {"m2pro": "M2~Pro", "gb10": "GB10", "any": "Value"}
    print("Knob & " + " & ".join(hdr[d] for d in dev_names)
          + " & Rule & Verification \\\\\n\\midrule")
    for name in order:
        vals = [_fmt_value(by_dev[d].get(name, {}).get("value")
                           if name in by_dev[d] else None)
                for d in dev_names]
        first = next((by_dev[d][name] for d in dev_names if name in by_dev[d]), {})
        rule = RULE_TEXT.get(first.get("rule", ""), _tex_escape(first.get("rule", "")))
        verif = _tex_escape(first.get("verification") or "---")
        print(f"{_tex_escape(name)} & " + " & ".join(vals)
              + f" & {rule} & {verif} \\\\")
    print("\\bottomrule\n\\end{tabular}\n\\end{table}\n")


def main() -> int:
    knobs = pl.load_knobs()
    if not knobs:
        sys.exit("knobs.yml not found — run derive_knobs.py first")
    print("% Generated by evaluation/pilots/generate_knob_tables.py — do not hand-edit.")
    print(f"% variants: {knobs.get('variants')}\n")
    for exp in ("e1", "e2", "e3", "e4", "e5", "e6"):
        devices = (knobs.get("experiments") or {}).get(exp)
        if devices:
            render_experiment(exp, devices, knobs)
    return 0


if __name__ == "__main__":
    sys.exit(main())
