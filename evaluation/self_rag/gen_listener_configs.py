#!/usr/bin/env python3
"""Generate the listener-ON twins of the serial configs.

Why a separate set rather than turning listeners on in place. The latency and
quality columns of 5.1 come from the EXISTING listener-off serial runs (R=4,
already collected on both devices). Re-collecting those under listeners would
throw away good data and fold an observer cost into the headline table. So the
counters come from a separate, shorter listener-on pass, and one paired
on/off cell bounds what the listeners themselves cost. The methods section
states the split.

What each device can actually report -- verified 2026-09-02, not assumed:

  m3pro   macmon: all/cpu/gpu/ane/ram/sys power, memory{ram_total, ram_usage,
          swap_*}, temps, per-cluster usage. Per-engine power is what 5.2's ANE
          arm needs. NOTE macmon lives in /opt/homebrew/bin, which is NOT on the
          PATH of a non-interactive ssh session -- the harness must add it or the
          listener fails to spawn and the run silently has no counters.

  gb10    dcgmi: on this stack the profiling fields are unavailable, so the
          field ladder falls to [155,156,200,201,203,204] = power, cumulative
          energy, PCIe TX/RX, GPU util, memory-copy util. No DRAM-bandwidth and
          no framebuffer field.
          top: CPU and MEMORY. This is the memory source on gb10, because
          `nvidia-smi memory.used` reports N/A on this unified-memory part --
          there is no discrete framebuffer to report. System memory IS the
          memory, on both devices.

    python evaluation/self_rag/gen_listener_configs.py [--dry-run]
"""
import argparse
import glob
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
CONFIGS = os.path.join(HERE, "configs")

# Keyed by the device token in the filename.
LISTENERS = {
    "mlx": ["macmon"],
    "cuda": ["dcgmi", "top"],
}


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    written = 0
    for src in sorted(glob.glob(os.path.join(CONFIGS, "*_serial_*.yml"))):
        base = os.path.basename(src)
        if "_obs_" in base or base.startswith("quantest"):
            continue
        device = base.rsplit("_", 1)[1].removesuffix(".yml")
        if device not in LISTENERS:
            continue
        dst = os.path.join(CONFIGS, base.replace(f"_serial_{device}.yml",
                                                 f"_serial_obs_{device}.yml"))
        cfg = yaml.safe_load(open(src))
        cfg["listeners"] = list(LISTENERS[device])
        cfg["name"] = f"{cfg.get('name', base)} [listeners on]"
        if args.dry_run:
            print(f"would write {os.path.basename(dst)}  listeners={cfg['listeners']}")
        else:
            with open(dst, "w") as f:
                f.write("# GENERATED by gen_listener_configs.py -- do not hand-edit.\n"
                        "# Listener-ON twin of the serial config; see that script for why\n"
                        "# the counters are collected separately from latency/quality.\n")
                yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=False)
            print(f"wrote {os.path.basename(dst)}  listeners={cfg['listeners']}")
        written += 1
    print(f"\n{written} config(s)")


if __name__ == "__main__":
    main()
